    def _apply_map(self, text: str, mapping: Dict[str, str]) -> str:
        tokens = re.findall(r"[\u0C80-\u0CFF]+|[^\s\u0C80-\u0CFF]+|\s+", text)
        res = [mapping.get(t, t) for t in tokens]
        return "".join(res)

